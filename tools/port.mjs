// Rebuild the core of ascii-sharks.js from upstream stackedlol/ascii-sharks (src/*.ts), by text only:
// Node's own type stripper removes the TypeScript, then import/export lines go. Nothing is executed.
//   node tools/port.mjs <upstream>/src            -> rewrites the core block of ascii-sharks.js
//   node tools/port.mjs <upstream>/src --check    -> exit 1 if the committed core block differs
import { stripTypeScriptTypes } from "node:module";
import fs from "node:fs";

const [src, flag] = process.argv.slice(2);
if (!src) { console.error("usage: node tools/port.mjs <upstream>/src [--check]"); process.exit(2); }
export function port(dir) {
  return ["math", "species", "world", "renderer", "engine"].map((f) => {
    let js = stripTypeScriptTypes(fs.readFileSync(`${dir}/${f}.ts`, "utf8"), { mode: "transform", sourceMap: false });
    js = js.replace(/^import [\s\S]*?;\n/gm, "").replace(/^export (?=(const|function|class|let) )/gm, "");
    return `// ---- ${f}.ts ----\n` + js.trim();
  }).join("\n\n").replace(/\n{3,}/g, "\n\n");
}
const FILE = new URL("../ascii-sharks.js", import.meta.url);
const BEGIN = "// ==== BEGIN CORE (generated by tools/port.mjs) ====\n", END = "\n// ==== END CORE ====";
const text = fs.readFileSync(FILE, "utf8");
const a = text.indexOf(BEGIN) + BEGIN.length, b = text.indexOf(END);
const core = port(src);
if (flag === "--check") {
  const same = text.slice(a, b) === core;
  console.log(same ? "core block matches upstream" : "core block DIFFERS from upstream");
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(FILE, text.slice(0, a) + core + text.slice(b));
console.log(`core block: ${core.split("\n").length} lines from ${src}`);
